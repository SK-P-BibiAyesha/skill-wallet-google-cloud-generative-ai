from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
)
from reportlab.lib.enums import TA_CENTER


def generate_pdf(
    filename,
    topic,
    transcript,
    similarity,
    overall,
    concept,
    quality,
    level,
    feedback,
):

    doc = SimpleDocTemplate(filename)

    styles = getSampleStyleSheet()

    title_style = styles["Heading1"]
    title_style.alignment = TA_CENTER
    title_style.textColor = colors.darkblue

    heading = styles["Heading2"]
    normal = styles["BodyText"]

    story = []

    # ----------------------------------------
    # Title
    # ----------------------------------------

    story.append(
        Paragraph(
            "Voice-Based Concept Understanding Analyser",
            title_style,
        )
    )

    story.append(
        Paragraph(
            "<b>Analysis Report</b>",
            heading,
        )
    )

    story.append(Spacer(1, 20))

    # ----------------------------------------
    # Topic
    # ----------------------------------------

    story.append(Paragraph("<b>Topic</b>", heading))
    story.append(Paragraph(topic, normal))
    story.append(Spacer(1, 12))

    # ----------------------------------------
    # Transcript
    # ----------------------------------------

    story.append(Paragraph("<b>Transcript</b>", heading))
    story.append(Paragraph(transcript, normal))
    story.append(Spacer(1, 12))

    # ----------------------------------------
    # Scores
    # ----------------------------------------

    story.append(Paragraph("<b>Analysis Scores</b>", heading))

    story.append(
        Paragraph(
            f"Semantic Similarity : {similarity:.2f}%",
            normal,
        )
    )

    story.append(
        Paragraph(
            f"Overall Score : {overall:.2f}%",
            normal,
        )
    )

    story.append(
        Paragraph(
            f"Concept Accuracy : {concept:.2f}%",
            normal,
        )
    )

    story.append(
        Paragraph(
            f"Explanation Quality : {quality:.2f}%",
            normal,
        )
    )

    story.append(Spacer(1, 12))

    # ----------------------------------------
    # Level
    # ----------------------------------------

    story.append(
        Paragraph(
            "<b>Understanding Level</b>",
            heading,
        )
    )

    story.append(
        Paragraph(level, normal)
    )

    story.append(Spacer(1, 12))

    # ----------------------------------------
    # Feedback
    # ----------------------------------------

    story.append(
        Paragraph(
            "<b>Feedback</b>",
            heading,
        )
    )

    story.append(
        Paragraph(feedback.replace("\n", "<br/>"), normal)
    )

    story.append(Spacer(1, 20))

    # ----------------------------------------
    # Footer
    # ----------------------------------------

    story.append(
        Paragraph(
            "<b>Generated by VBCUA AI System</b>",
            title_style,
        )
    )

    doc.build(story)