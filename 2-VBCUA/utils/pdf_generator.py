
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
)


def safe_paragraph_text(value):
    """Escape user-provided text before passing it to ReportLab."""
    return escape(str(value if value is not None else ""))


def generate_pdf(
    filename,
    topic,
    transcript,
    similarity,
    overall,
    concept,
    quality,
    level,
    feedback,
):
    doc = SimpleDocTemplate(filename)
    styles = getSampleStyleSheet()

    title_style = styles["Heading1"]
    title_style.alignment = TA_CENTER
    title_style.textColor = colors.darkblue

    heading = styles["Heading2"]
    normal = styles["BodyText"]

    story = []

    # Title
    story.append(
        Paragraph(
            "Voice-Based Concept Understanding Analyser",
            title_style,
        )
    )
    story.append(Paragraph("<b>Analysis Report</b>", heading))
    story.append(Spacer(1, 20))

    # Topic
    story.append(Paragraph("<b>Topic</b>", heading))
    story.append(Paragraph(safe_paragraph_text(topic), normal))
    story.append(Spacer(1, 12))

    # Transcript
    story.append(Paragraph("<b>Transcript</b>", heading))
    story.append(Paragraph(safe_paragraph_text(transcript), normal))
    story.append(Spacer(1, 12))

    # Scores
    story.append(Paragraph("<b>Analysis Scores</b>", heading))

    story.append(
        Paragraph(
            f"Semantic Similarity: {float(similarity):.2f}%",
            normal,
        )
    )
    story.append(
        Paragraph(
            f"Overall Score: {float(overall):.2f}%",
            normal,
        )
    )
    story.append(
        Paragraph(
            f"Concept Accuracy: {float(concept):.2f}%",
            normal,
        )
    )
    story.append(
        Paragraph(
            f"Explanation Quality: {float(quality):.2f}%",
            normal,
        )
    )
    story.append(Spacer(1, 12))

    # Understanding level
    story.append(Paragraph("<b>Understanding Level</b>", heading))
    story.append(Paragraph(safe_paragraph_text(level), normal))
    story.append(Spacer(1, 12))

    # Feedback: escape text, then safely add line-break markup
    safe_feedback = safe_paragraph_text(feedback)
    safe_feedback = safe_feedback.replace("\r\n", "\n")
    safe_feedback = safe_feedback.replace("\r", "\n")
    safe_feedback = safe_feedback.replace("\n", "<br/>")

    story.append(Paragraph("<b>Feedback</b>", heading))
    story.append(Paragraph(safe_feedback, normal))
    story.append(Spacer(1, 20))

    # Footer
    story.append(
        Paragraph(
            "<b>Generated by VBCUA AI System</b>",
            title_style,
        )
    )

    doc.build(story)
